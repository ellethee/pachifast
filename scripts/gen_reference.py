"""Generate the reference pages of the documentation from the code.

Run ``uv run python scripts/gen_reference.py`` after changing a setting, a message or a CLI option; a test fails when
the committed pages are out of date.
"""

import json
import os
import re
import tomllib
from pathlib import Path

import typer.main

os.environ.setdefault("PACHIFAST_SECRET_KEY", "x" * 40)

from pachifast.cli.app import app  # noqa: E402
from pachifast.config.schema import build_config_schema  # noqa: E402
from pachifast.config.sections import SECTIONS  # noqa: E402
from pachifast.i18n.locale import en, it  # noqa: E402

REFERENCE_DIR = Path(__file__).resolve().parent.parent / "docs" / "reference"
ROOT = REFERENCE_DIR.parent.parent
BANNER = "<!-- Generated by scripts/gen_reference.py: do not edit by hand. -->\n\n"
#: hand-written files that show the version between ``<!-- version -->`` markers; this script keeps them in step
STAMPED = ("README.md", "README.it.md", "docs/index.md")
MARKERS = re.compile(r"(<!-- version -->).*?(<!-- /version -->)")


def project_version() -> str:
    """The version in ``pyproject.toml``: the single place where it is written."""
    return tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]


def _for_version() -> str:
    """The line under the title of a generated page."""
    return f"Generated for pachifast **{project_version()}**.\n"


def _cell(text: object) -> str:
    """A value safe inside a markdown table cell."""
    return str(text).replace("|", "\\|").replace("\n", " ")


def _type_name(prop: dict) -> str:
    """Readable type of a JSON Schema property."""
    if "enum" in prop and prop.get("type") == "string" and len(prop["enum"]) > 1:
        return " \\| ".join(f"`{value}`" if value else '`""`' for value in prop["enum"])
    if "anyOf" in prop:
        return "list or comma-separated string"
    return {"string": "string", "integer": "integer", "boolean": "boolean", "number": "number"}.get(
        prop.get("type", ""), prop.get("type", "")
    )


def settings_page() -> str:
    """``reference/settings.md``: every key of ``pachifast.yaml`` with type, default and description."""
    schema = build_config_schema()
    lines = [
        BANNER,
        "# Settings reference\n",
        _for_version(),
        "Every setting can be given in a section of `pachifast.yaml` (`section.key`, case-insensitive), as an "
        "environment variable `PACHIFAST_<NAME>` or in `.env`; see "
        "[Configuration](../guides/configuration.md) for the priority between sources. "
        "A [JSON Schema](pachifast.schema.json) of the file is available for editors.\n",
        "| Setting | YAML | Environment variable | Type | Default | Description |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for section, section_schema in schema["properties"].items():
        lines.append(f"| **{section}** | | | | | {_cell(section_schema.get('description', ''))} |")
        for (key, field), prop in zip(SECTIONS[section], section_schema["properties"].values(), strict=True):
            default = prop.get("default", "")
            if isinstance(default, bool):
                default = str(default).lower()
            shown = "" if default in ("", [], None) else f"`{default}`"
            lines.append(
                f"| `{field}` | `{section}.{key}` | `PACHIFAST_{field.upper()}` | {_type_name(prop)} | "
                f"{_cell(shown)} | {_cell(prop.get('description', ''))} |"
            )
    return "\n".join(lines) + "\n"


def error_codes_page() -> str:
    """``reference/error-codes.md``: every message code of the core with its English and Italian text."""
    lines = [
        BANNER,
        "# Message codes\n",
        _for_version(),
        "Every error carries a stable `code` (and `params` for its `{placeholders}`); clients translate from the code. "
        "See [Errors and i18n](../guides/errors-and-i18n.md). Codes of your own modules are listed by "
        "`pachifast locale check`.\n",
        "| Code | English | Italian |",
        "| --- | --- | --- |",
    ]
    for code in sorted(en.MESSAGES):
        lines.append(f"| `{code}` | {_cell(en.MESSAGES[code])} | {_cell(it.MESSAGES.get(code, ''))} |")
    return "\n".join(lines) + "\n"


def _options(command) -> list[str]:
    """Table rows of the arguments and options of a command."""
    rows = []
    for param in command.params:
        if param.param_type_name == "argument":
            names = f"`{param.name}`" + ("" if param.required else " (optional)")
        else:
            names = ", ".join(f"`{opt}`" for opt in [*param.opts, *param.secondary_opts])
        default = getattr(param, "default", None)
        shown = "" if default in (None, "", False, ()) or callable(default) else f"`{default}`"
        rows.append(f"| {names} | {_cell(getattr(param, 'help', '') or '')} | {_cell(shown)} |")
    return rows


def cli_page() -> str:
    """``reference/cli.md``: every command of ``pachifast`` with its arguments and options."""
    root = typer.main.get_command(app)
    out = [
        BANNER,
        "# CLI reference\n",
        _for_version(),
        "Run `pachifast <command> --help` for the same information in the terminal. "
        "Commands that read a project accept `--base-dir` (the project root, default `.`).\n",
    ]
    for name in sorted(root.commands):
        command = root.commands[name]
        if hasattr(command, "commands"):
            out.append(f"## `pachifast {name}`\n\n{(command.help or '').strip()}\n")
            for sub in sorted(command.commands):
                subcommand = command.commands[sub]
                out.append(f"### `pachifast {name} {sub}`\n\n{(subcommand.help or '').strip()}\n")
                rows = [row for row in _options(subcommand) if "`--help`" not in row]
                if rows:
                    out += ["| Argument / option | Description | Default |", "| --- | --- | --- |", *rows, ""]
        else:
            out.append(f"## `pachifast {name}`\n\n{(command.help or '').strip()}\n")
            rows = [row for row in _options(command) if "`--help`" not in row]
            if rows:
                out += ["| Argument / option | Description | Default |", "| --- | --- | --- |", *rows, ""]
    return "\n".join(out) + "\n"


def changelog_page() -> str:
    """``docs/changelog.md``: the changelog of the repository root, so the site (built from docs/) includes it."""
    root = REFERENCE_DIR.parent.parent
    return BANNER + (root / "CHANGELOG.md").read_text(encoding="utf-8")


def stamped_files() -> dict[Path, str]:
    """The hand-written files that show the version, with the current one written in the markers."""
    version = project_version()
    out = {}
    for name in STAMPED:
        path = ROOT / name
        text = path.read_text(encoding="utf-8")
        if not MARKERS.search(text):
            raise SystemExit(f"{name} has no <!-- version -->...<!-- /version --> markers")
        out[path] = MARKERS.sub(lambda m: f"{m.group(1)}{version}{m.group(2)}", text)
    return out


def pages() -> dict[Path, str]:
    """Every generated page by path."""
    return {
        **stamped_files(),
        REFERENCE_DIR.parent / "changelog.md": changelog_page(),
        REFERENCE_DIR / "settings.md": settings_page(),
        REFERENCE_DIR / "error-codes.md": error_codes_page(),
        REFERENCE_DIR / "cli.md": cli_page(),
        REFERENCE_DIR / "pachifast.schema.json": json.dumps(build_config_schema(), indent=2, ensure_ascii=False) + "\n",
    }


def main() -> None:
    """Write the pages."""
    for path, text in pages().items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(REFERENCE_DIR.parent.parent)}")


if __name__ == "__main__":
    main()
