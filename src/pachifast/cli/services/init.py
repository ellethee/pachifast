"""Project bootstrap service behind ``pachifast init``.

Steps (each one is idempotent, so ``init`` can be run again safely):

1. create or complete ``.env`` with ``PACHIFAST_SECRET_KEY`` and ``PACHIFAST_AUTH_DATABASE_URL``;
2. create the Alembic layout, the first autogenerated revision and apply the migrations;
3. create the first superuser, unless it already exists.
"""

import os
import secrets
from dataclasses import dataclass, field
from pathlib import Path

from sqlalchemy.engine import make_url
from sqlalchemy.exc import ArgumentError

from pachifast import migrations as migrations_api
from pachifast.cli.services import users as users_service
from pachifast.config.yaml_source import load_config_data

SECRET_KEY_VAR = "PACHIFAST_SECRET_KEY"
DATABASE_URL_VAR = "PACHIFAST_AUTH_DATABASE_URL"
INITIAL_REVISION_MESSAGE = "init"


@dataclass
class InitReport:
    """What ``init`` did, step by step, to be shown to the user."""

    env_file: Path
    env_created: bool
    env_keys_written: list[str] = field(default_factory=list)
    layout_created: bool = False
    revision_created: bool = False
    user_created: bool = False
    username: str | None = None


def default_database_url(root: Path) -> str:
    """Return the default SQLite URL (``db.sqlite3`` in the project root)."""
    return f"sqlite+aiosqlite:///{root / 'db.sqlite3'}"


def _parse_env(lines: list[str]) -> dict[str, str]:
    """Parse ``KEY=VALUE`` lines of a dotenv file, ignoring comments and blank lines."""
    values: dict[str, str] = {}
    for line in lines:
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, value = stripped.partition("=")
        values[key.strip()] = value.strip().strip("'\"")
    return values


def _safe_url(url: str) -> str:
    """Return ``url`` with the password masked, for messages."""
    try:
        return make_url(url).render_as_string(hide_password=True)
    except ArgumentError:
        return "<invalid URL>"


def _check_no_environment_conflict(values: dict[str, str]) -> None:
    """Refuse to continue when a real environment variable would override the value that ends up in ``.env``.

    Environment variables win over ``.env`` at runtime, so a stale ``export`` (for example from a previous demo)
    would silently make the project use the wrong secret or database.

    Raises:
        ValueError: Naming the variable, with a hint on how to fix it (secret values are never printed).
    """
    for key in (SECRET_KEY_VAR, DATABASE_URL_VAR):
        current = os.environ.get(key)
        if not current or current == values[key]:
            continue
        shown = f" ({_safe_url(current)})" if key == DATABASE_URL_VAR else ""
        fix = f"Run `unset {key}` and try again, so that `init` writes its own value in .env"
        raise ValueError(
            f"{key} is already set in your environment{shown} and would override the value in .env, "
            f"which was left untouched. {fix}. To keep the value from the environment, copy it into .env "
            f"({key}=...) and run `init` again."
        )


def _check_sqlite_location(database_url: str) -> None:
    """For a file based SQLite URL, check that the target directory exists and is writable.

    Raises:
        ValueError: With the directory and the (masked) URL, instead of SQLite's generic
            "unable to open database file".
    """
    try:
        url = make_url(database_url)
    except ArgumentError:
        return
    if not url.drivername.startswith("sqlite") or not url.database or url.database == ":memory:":
        return
    directory = Path(url.database).resolve().parent
    if not directory.is_dir():
        raise ValueError(f"SQLite database directory does not exist: {directory} (URL: {_safe_url(database_url)}).")
    if not os.access(directory, os.W_OK):
        raise ValueError(f"SQLite database directory is not writable: {directory} (URL: {_safe_url(database_url)}).")


def ensure_env_file(root: Path, database_url: str | None = None) -> tuple[Path, bool, dict[str, str], list[str]]:
    """Create ``.env`` or fill in the missing/empty required variables, never overwriting real values.

    A value already defined in the YAML config file is not copied into ``.env`` (``.env`` would override it),
    unless it is given explicitly (``database_url``).

    Returns:
        ``(path, created, effective_values, written_keys)``: the values in effect (``.env``, else YAML).
    """
    env_path = root / ".env"
    created = not env_path.exists()
    lines = env_path.read_text(encoding="utf-8").splitlines() if not created else []
    current = _parse_env(lines)
    yaml_data = load_config_data(root)
    from_yaml = {
        key: str(value)
        for key, name in ((SECRET_KEY_VAR, "secret_key"), (DATABASE_URL_VAR, "auth_database_url"))
        if (value := yaml_data.get(name))
    }

    wanted = {
        SECRET_KEY_VAR: lambda: secrets.token_hex(32),
        DATABASE_URL_VAR: lambda: database_url or default_database_url(root),
    }
    written: list[str] = []
    for key, make_value in wanted.items():
        if current.get(key):
            continue
        if key in from_yaml and not (key == DATABASE_URL_VAR and database_url):
            current[key] = from_yaml[key]
            continue
        value = make_value()
        new_line = f"{key}={value}"
        for index, line in enumerate(lines):
            if line.strip().startswith(f"{key}="):
                lines[index] = new_line
                break
        else:
            lines.append(new_line)
        current[key] = value
        written.append(key)

    _check_no_environment_conflict(current)
    _check_sqlite_location(current[DATABASE_URL_VAR])

    if written:
        env_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        if created:
            env_path.chmod(0o600)
    return env_path, created, current, written


def _apply_to_environment(values: dict[str, str]) -> None:
    """Export the project variables to this process (real environment variables win) and reset settings."""
    from pachifast.config import get_settings

    for key in (SECRET_KEY_VAR, DATABASE_URL_VAR):
        os.environ.setdefault(key, values[key])
    get_settings.cache_clear()


def _has_revisions(root: Path, target_name: str) -> bool:
    """True if the target already has at least one revision file."""
    versions_dir = root / "migrations" / target_name / "versions"
    return versions_dir.exists() and any(versions_dir.glob("*.py"))


def init_project(
    *,
    base_dir: str = ".",
    username: str = "admin",
    password: str | None = None,
    email: str | None = None,
    database_url: str | None = None,
    target_name: str = "auth",
    create_user: bool = True,
) -> InitReport:
    """Bootstrap a generated project: ``.env``, migrations and first superuser.

    Args:
        base_dir: Project root containing ``project_modules.py``.
        username: Username of the superuser to create.
        password: Password of the superuser (required when ``create_user`` is true).
        email: Optional email of the superuser.
        database_url: Auth database URL; defaults to a SQLite file in the project root.
        target_name: Migration target holding the auth tables.
        create_user: Whether to create the superuser.

    Raises:
        FileNotFoundError: If ``base_dir`` is not a generated project.
        ValueError: If a password is needed but missing, or it violates the policy.
    """
    root = Path(base_dir).resolve()
    if not (root / "project_modules.py").exists():
        raise FileNotFoundError(
            f"project_modules.py not found in {root}. Run `pachifast init` from a generated project "
            "(see `pachifast new project <name>`), or use --base-dir."
        )
    if create_user and not password:
        raise ValueError("A password is required to create the superuser.")
    if create_user:
        users_service.check_password_policy(password)

    env_path, env_created, values, written = ensure_env_file(root, database_url)
    _apply_to_environment(values)
    report = InitReport(env_file=env_path, env_created=env_created, env_keys_written=written)

    if not (root / "migrations" / target_name / "env.py").exists():
        migrations_api.create_migration_layout(base_dir=str(root), target_name=target_name)
        report.layout_created = True
    if not _has_revisions(root, target_name):
        migrations_api.revision(
            base_dir=str(root), target_name=target_name, message=INITIAL_REVISION_MESSAGE, autogenerate=True
        )
        report.revision_created = True
    migrations_api.upgrade(base_dir=str(root), target_name=target_name, revision_id="head")

    if create_user:
        report.username = username.strip().lower()
        existing = users_service.list_users(report.username, base_dir=str(root))
        if any(user["username"] == report.username for user in existing):
            return report
        assert password is not None  # guaranteed by the check above
        users_service.create_user(
            username,
            base_dir=str(root),
            password=password,
            email=email,
            is_staff=True,
            is_superuser=True,
        )
        report.user_created = True
    return report
