def app_template_root(app_name: str) -> str:
    """Return the router module of a new app."""
    return f"""
    from pachifast.router_factory import get_router

    router = get_router()


    @router.get("", summary="Health endpoint for {app_name}")
    async def read_{app_name}():
        return {{"module": "{app_name}", "status": "ok"}}
    """


def app_template_module(app_name: str, with_db: bool = False) -> str:
    """Return the ``module.py`` descriptor of a new app."""
    if with_db:
        return f"""
        from pachifast import AppModule, MigrationTarget

        module = AppModule(
            name="{app_name}",
            kind="app",
            router_modules=("apps.{app_name}.root",),
            settings_modules=("apps.{app_name}.settings",),
            locale_package="apps.{app_name}.locale",
            migration_targets=(
                MigrationTarget(
                    name="{app_name}",
                    database_url_resolver="apps.{app_name}.settings:get_database_url",
                    model_modules=("apps.{app_name}.models",),
                ),
            ),
        )
        """
    return f"""
    from pachifast import AppModule

    module = AppModule(
        name="{app_name}",
        kind="app",
        router_modules=("apps.{app_name}.root",),
        locale_package="apps.{app_name}.locale",
    )
    """


def locale_template(module_name: str, language: str = "en") -> str:
    """Return a ``locale/<language>.py`` file of a new module (empty, with an example)."""
    return f'''
    """Messages of {module_name} in {language}: stable code -> text.

    The code is the contract with the clients; keep the same codes and {{fields}} in every language
    (`pachifast locale check`), and use the module name as the first part of each code.
    """

    MESSAGES: dict[str, str] = {{
        # "{module_name}.item_not_found": "Item {{number}} not found",
    }}
    '''


