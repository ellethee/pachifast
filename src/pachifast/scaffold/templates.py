"""Text templates used to generate projects, apps and common modules."""

import json

from pachifast.scaffold.helpers import normalize_name
from pachifast.scaffold.metadata import ProjectMetadata, requirement_name

PACKAGE_NAME = "pachifast"
# Raise it when the generated code needs a newer pachifast (0.7: registration closed by default).
PACKAGE_MIN_VERSION = "0.7.0"


def _toml_string(value: str) -> str:
    """Return ``value`` as a TOML basic string (JSON escaping is a valid subset)."""
    return json.dumps(value, ensure_ascii=False)


def project_template_pyproject(project_name: str, metadata: ProjectMetadata | None = None) -> str:
    """Return a PEP 621 ``pyproject.toml`` (uv-managed) for a new project.

    Optional metadata (author, license, keywords, URLs) is written only when provided.
    """
    meta = (metadata or ProjectMetadata()).normalized()
    lines = [
        "[project]",
        f"name = {_toml_string(project_name)}",
        f"version = {_toml_string(meta.version)}",
        f"description = {_toml_string(meta.description)}",
        'readme = "README.md"',
        f"requires-python = {_toml_string(meta.requires_python)}",
    ]
    if meta.license:
        lines.append(f"license = {_toml_string(meta.license)}")
    if meta.author or meta.author_email:
        fields = []
        if meta.author:
            fields.append(f"name = {_toml_string(meta.author)}")
        if meta.author_email:
            fields.append(f"email = {_toml_string(meta.author_email)}")
        lines.append(f"authors = [{{ {', '.join(fields)} }}]")
    if meta.keywords:
        lines.append(f"keywords = [{', '.join(_toml_string(keyword) for keyword in meta.keywords)}]")
    lines += _toml_list("dependencies", _runtime_dependencies(meta.packages))

    urls = {"Homepage": meta.homepage, "Repository": meta.repository}
    if any(urls.values()):
        lines += ["", "[project.urls]"]
        lines += [f"{label} = {_toml_string(url)}" for label, url in urls.items() if url]
    if meta.dev_packages:
        lines += ["", "[dependency-groups]", *_toml_list("dev", _unique_requirements(meta.dev_packages))]
    return "\n".join(lines) + "\n"


def _toml_list(key: str, items: list[str]) -> list[str]:
    """Return the lines of a multi-line TOML array of strings."""
    return [f"{key} = [", *(f"    {_toml_string(item)}," for item in items), "]"]


def _unique_requirements(requirements: list[str]) -> list[str]:
    """Drop repeated requirements of the same distribution, keeping the last one given."""
    by_name = {requirement_name(item): item for item in requirements}
    return list(by_name.values())


def _runtime_dependencies(extra: list[str]) -> list[str]:
    """``pachifast`` first, then the extra packages; an extra ``pachifast`` requirement replaces the default."""
    default = f"{PACKAGE_NAME}>={PACKAGE_MIN_VERSION}"
    merged = _unique_requirements([default, *extra])
    return sorted(merged, key=lambda item: requirement_name(item) != PACKAGE_NAME)


def project_template_main() -> str:
    """Return the ``main.py`` entry point of a new project."""
    return """
    from pachifast import create_app

    from project_modules import MODULES

    app = create_app(
        MODULES,
        cors_origins=[
            "http://localhost",
            "http://127.0.0.1:8000",
        ],
    )
    """


def project_template_modules() -> str:
    """Return the ``project_modules.py`` registry of a new project."""
    return """
    from pachifast.presets import core_module

    MODULES = (
        core_module,
    )
    """


def project_template_readme(project_name: str) -> str:
    """Return the README of a new project."""
    return f"""
    # {project_name}

    Minimal FastAPI project generated by `pachifast`.

    ## Quick start

    ```bash
    uv sync
    uv run pachifast init     # .env, migrations and first superuser
    uv run pachifast dev
    ```
    """


def project_template_config_yaml() -> str:
    """Return the sample ``pachifast.yaml`` of a new project (all values optional)."""
    return """
    # yaml-language-server: $schema=./pachifast.schema.json
    # Optional project configuration. Environment variables (PACHIFAST_*, also from .env) take
    # precedence over the values in this file. Keys are the setting names, case-insensitive.

    # Address of the development server (`pachifast dev`; --host/--port override it).
    host: 127.0.0.1
    port: 8000

    # Examples:
    # debug: true      # off by default; on shows the traceback page to clients: development only
    # access_token_expire_minutes: 30
    # disable_core_routers: [permissions]
    # disable_core_routes: [/user/settings]
    # default_locale: it            # language of the API error messages (en, it); every error also has a stable `code`
    # use_accept_language: true     # pick the language from the Accept-Language header of each request

    # Keep secrets (secret_key, database URLs with passwords) in .env, not here.
    """


def project_template_env_example() -> str:
    """Return the ``.env.example`` file of a new project."""
    return """
    # Secret used to sign tokens. Required: the app refuses to start without it.
    # Generate one with:  openssl rand -hex 32
    PACHIFAST_SECRET_KEY=
    """


