def db_settings_template(name: str, with_db: bool = False) -> str:
    """Return the ``settings.py`` of a module (optionally with a database URL)."""
    env_prefix = name.upper()
    field_prefix = normalize_name(name).lower()
    enabled_field = f"{field_prefix}_enabled"
    database_url_field = f"{field_prefix}_database_url"
    fields = [f'    {enabled_field}: bool = Field(default=True, validation_alias="{env_prefix}_ENABLED")']
    extra_funcs = ""
    if with_db:
        fields.append(
            f'    {database_url_field}: str = Field(default="", validation_alias="{env_prefix}_DATABASE_URL")'
        )
        extra_funcs = f"""


def get_database_url() -> str:
    return settings.{database_url_field}
"""
    fields_block = "\n".join(fields)
    return f"""
from pydantic import Field

from pachifast.config import PachifastSettingsBase


class Settings(PachifastSettingsBase):
{fields_block}


settings = Settings(){extra_funcs}
"""


def db_models_template(name: str) -> str:
    """Return the example ``models.py`` of a module with its own database."""
    table_name = f"{normalize_name(name).lower()}_example"
    class_name = "".join(part.capitalize() for part in normalize_name(name).split("_")) + "Example"
    return f"""
    from sqlalchemy import String
    from sqlalchemy.orm import Mapped, mapped_column

    from pachifast.database import Base


    class {class_name}(Base):
        __tablename__ = "{table_name}"

        id: Mapped[int | None] = mapped_column(primary_key=True, default=None, nullable=False)
        name: Mapped[str] = mapped_column(String(120))
    """
