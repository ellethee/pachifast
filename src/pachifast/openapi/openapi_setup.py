"""Helpers for split OpenAPI schemas and Swagger UI endpoints."""

from __future__ import annotations

from logging import getLogger
from pprint import pformat

from fastapi import APIRouter, FastAPI
from fastapi.openapi.docs import get_swagger_ui_html, get_swagger_ui_oauth2_redirect_html
from fastapi.responses import HTMLResponse, JSONResponse
from fastapi.routing import APIWebSocketRoute

from pachifast.modules import ModuleKind

log = getLogger(__name__)

DOCS_OAUTH2_REDIRECT_URL = "/docs/oauth2-redirect"
CORE_OPENAPI_URL = "/api/v1/openapi-core.json"
APPS_OPENAPI_URL = "/api/v1/openapi-apps.json"
DEFAULT_OPENAPI_URL = "/api/v1/openapi.json"


def install_openapi_endpoints(app: FastAPI, mounts: list[tuple[APIRouter, str]]) -> None:
    """Register OpenAPI JSON and Swagger UI endpoints on the given app.

    The framework exposes:

    - one full schema for programmatic consumers
    - one schema and docs UI for `core`
    - one schema and docs UI for `app` and `common`

    ``mounts`` is the list of ``(router, mount_prefix)`` pairs included in the app: schemas are
    built from these routers, so they do not depend on how FastAPI stores included routes.
    """
    app.openapi = lambda: build_openapi_schema(app, mounts=mounts, cache_key="all")

    @app.get(DEFAULT_OPENAPI_URL, include_in_schema=False)
    async def openapi_all() -> JSONResponse:
        return JSONResponse(build_openapi_schema(app, mounts=mounts, cache_key="all"))

    @app.get(CORE_OPENAPI_URL, include_in_schema=False)
    async def openapi_core() -> JSONResponse:
        return JSONResponse(
            build_openapi_schema(
                app,
                mounts=mounts,
                allowed_module_kinds={"core"},
                cache_key="core",
                title_suffix="Core API",
            )
        )

    @app.get(APPS_OPENAPI_URL, include_in_schema=False)
    async def openapi_apps() -> JSONResponse:
        return JSONResponse(
            build_openapi_schema(
                app,
                mounts=mounts,
                allowed_module_kinds={"app", "common"},
                cache_key="apps",
                title_suffix="Apps API",
            )
        )

    @app.get("/docs", include_in_schema=False)
    async def swagger_apps() -> HTMLResponse:
        return _swagger_ui_html(app, openapi_url=APPS_OPENAPI_URL, title_suffix="Apps")

    @app.get("/docs/core", include_in_schema=False)
    async def swagger_core() -> HTMLResponse:
        return _swagger_ui_html(app, openapi_url=CORE_OPENAPI_URL, title_suffix="Core")

    @app.get("/docs/oauth2-redirect", include_in_schema=False)
    async def swagger_redirect() -> HTMLResponse:
        return get_swagger_ui_oauth2_redirect_html()


def build_openapi_schema(
    app: FastAPI,
    *,
    mounts: list[tuple[APIRouter, str]],
    allowed_module_kinds: set[ModuleKind] | None = None,
    cache_key: str,
    title_suffix: str | None = None,
) -> dict:
    """Build and cache an OpenAPI schema filtered by module kind.

    The schema is generated by a throwaway FastAPI app that includes only the selected
    routers with their mount prefix.
    """
    cache = getattr(app.state, "pachifast_openapi_cache", None)
    if cache is None:
        cache = {}
        app.state.pachifast_openapi_cache = cache
    if cache_key in cache:
        return cache[cache_key]

    selected = [
        (router, prefix)
        for router, prefix in mounts
        if allowed_module_kinds is None or getattr(router, "pachifast_module_kind", None) in allowed_module_kinds
    ]
    schema_app = FastAPI(
        title=_schema_title(app, title_suffix),
        version=app.version,
        description=app.description,
        docs_url=None,
        redoc_url=None,
        openapi_url=None,
    )
    for router, prefix in selected:
        schema_app.include_router(router, prefix=prefix)
    schema = schema_app.openapi()
    schema["schemes"] = ["https", "wss"]
    _append_websocket_paths(schema, selected)
    cache[cache_key] = schema
    log.debug("OpenAPI paths (%s): %s", cache_key, pformat(sorted(schema.get("paths", {}).keys())))
    return schema


def _append_websocket_paths(schema: dict, selected: list[tuple[APIRouter, str]]) -> None:
    """Add the WebSocket routes of the selected routers to the schema (``x-websocket``)."""
    for router, prefix in selected:
        tags = list(getattr(router, "tags", []))
        for route in router.routes:
            if not isinstance(route, APIWebSocketRoute):
                continue
            full_path = f"{prefix}{route.path}".replace("//", "/")
            schema.setdefault("paths", {})[full_path] = {
                "x-websocket": True,
                "get": {
                    "summary": route.name,
                    "operationId": _websocket_operation_id(route),
                    "description": route.__doc__ or "WebSocket endpoint",
                    "tags": tags,
                    "responses": {},
                },
            }


def _schema_title(app: FastAPI, suffix: str | None) -> str:
    return f"{app.title} - {suffix}" if suffix else app.title


def _websocket_operation_id(route: APIWebSocketRoute) -> str:
    """Return a stable OpenAPI operationId for a WebSocket route.

    FastAPI's default unique-id generator expects HTTP routes exposing
    `route.methods`; `APIWebSocketRoute` does not provide that attribute.
    """
    route_name = (route.name or "websocket").replace(" ", "_")
    route_path = route.path.replace("/", "_").replace("{", "").replace("}", "").strip("_")
    suffix = route_path or "root"
    return f"ws_{route_name}_{suffix}"


def _swagger_ui_html(app: FastAPI, *, openapi_url: str, title_suffix: str) -> HTMLResponse:
    return get_swagger_ui_html(
        openapi_url=openapi_url,
        title=f"{app.title} - {title_suffix}",
        oauth2_redirect_url=DOCS_OAUTH2_REDIRECT_URL,
    )
